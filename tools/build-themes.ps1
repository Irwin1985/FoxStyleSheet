<#
.SYNOPSIS
    Writes the themes\*.fss into foxstylesheet.prg, so that link("Word", ThisForm)
    works with nothing else to copy.

.DESCRIPTION
    The .fss files are the source. This script regenerates the region between the
    BEGIN and END markers at the end of foxstylesheet.prg: one FssBuiltInTheme()
    function with a TEXT block per theme, and FssBuiltInThemeNames(). Run it after
    changing any theme; tests\FoxStyleSheetRegressionTests.prg checks that the two
    say the same.

    ASCII only: PowerShell 5.1 misreads a .ps1 with accents (tooling-rules.md, rule 7).

.EXAMPLE
    .\tools\build-themes.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$root   = Split-Path $PSScriptRoot -Parent
$prg    = Join-Path $root 'foxstylesheet.prg'
$cp1252 = [Text.Encoding]::GetEncoding(1252)
$begin  = '*-- BEGIN BUILT-IN THEMES'
$end    = '*-- END BUILT-IN THEMES'

$themes = Get-ChildItem (Join-Path $root 'themes') -Filter '*.fss' | Sort-Object Name
if ($themes.Count -eq 0) { Write-Error 'No themes\*.fss found'; exit 1 }

$out = New-Object System.Collections.Generic.List[string]
$out.Add($begin)
$out.Add('*-- Generated by tools\build-themes.ps1 from themes\*.fss: do not edit by hand,')
$out.Add('*-- change the .fss and run the script again.')
$out.Add('*==============================================================')
$out.Add('FUNCTION FssBuiltInTheme')
$out.Add('    LPARAMETERS tcName')
$out.Add('    LOCAL lcTheme')
$out.Add('    lcTheme = ""')
$out.Add('    DO CASE')
foreach ($t in $themes) {
    $name = [IO.Path]::GetFileNameWithoutExtension($t.Name)
    $text = [IO.File]::ReadAllText($t.FullName, $cp1252)
    $lines = $text -split "`r?`n"
    foreach ($l in $lines) {
        if ($l.Trim().ToUpper().StartsWith('ENDTEXT')) { Write-Error "$($t.Name): a line starts with ENDTEXT"; exit 1 }
    }
    $out.Add(('    CASE LOWER(tcName) == "{0}"' -f $name.ToLower()))
    $out.Add('        TEXT TO lcTheme NOSHOW')
    foreach ($l in $lines) { $out.Add($l) }
    $out.Add('        ENDTEXT')
}
$out.Add('    ENDCASE')
$out.Add('    RETURN lcTheme')
$out.Add('ENDFUNC')
$out.Add('')
$out.Add('FUNCTION FssBuiltInThemeNames')
$names = ($themes | ForEach-Object { [IO.Path]::GetFileNameWithoutExtension($_.Name) }) -join ','
$out.Add(('    RETURN "{0}"' -f $names))
$out.Add('ENDFUNC')
$out.Add($end)
$region = ($out -join "`r`n")

$source = [IO.File]::ReadAllText($prg, $cp1252)
$a = $source.IndexOf($begin)
if ($a -ge 0) {
    $b = $source.IndexOf($end, $a)
    if ($b -lt 0) { Write-Error "foxstylesheet.prg has '$begin' but not '$end'"; exit 1 }
    $source = $source.Substring(0, $a) + $region + $source.Substring($b + $end.Length)
} else {
    $source = $source.TrimEnd() + "`r`n`r`n*==============================================================`r`n" + $region + "`r`n"
}
[IO.File]::WriteAllText($prg, $source, $cp1252)
Write-Host ("{0} themes written into foxstylesheet.prg: {1}" -f $themes.Count, $names)
exit 0
